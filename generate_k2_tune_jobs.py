#!/usr/bin/env python
# Usage:       python generate_k2_tune_jobs.py [--arms lr1e3 wr100 ...] [--seeds 1-16] [--out-dir jobs/multisource_k2_tune]
# Description: Writes PBS scripts (NOT submitted) for the honest K=2-only tuning study on K2_separated_static: one job per
#              (arm, seed), each calling run_k2_tune.py (new driver; no existing code touched). Also writes one submit
#              script per arm group (submit_A_lr.sh, submit_B_restarts.sh, submit_D_variants.sh). Never overwrites files.
#              Tag = k2tune_<arm>_seed<S>, save root saved/multisource_k2_tune/. PBS template copied from
#              generate_k2_test_jobs.py (qintel_wfly, ppn=2, 8gb, 1h).
# Date:        2026-10-09

import argparse
import os

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
ALBUM = 'synthetic/multisource/clean_scenarios/K2_separated_static.npz'
SAVE_ROOT = 'saved/multisource_k2_tune'

# arm -> (group, epochs, extra run_k2_tune.py flags, description)
ARMS = {
    'base':    ('A_lr', 300, '', 'baseline cosine 300 with early_stop=epochs (same early_stop as every other arm)'),
    'lr1e3':   ('A_lr', 300, "--optimizer-args '{\"lr\":1e-3}'", 'peak lr 1e-3, cosine 300'),
    'lr3e3':   ('A_lr', 300, "--optimizer-args '{\"lr\":3e-3}'", 'peak lr 3e-3, cosine 300'),
    'wr100':   ('B_restarts', 300, "--lr-scheduler '{\"type\":\"CosineAnnealingWarmRestarts\",\"args\":{\"T_0\":100}}'",
                'warm restarts T_0=100, 300 epochs'),
    'wr50x2':  ('B_restarts', 350, "--lr-scheduler '{\"type\":\"CosineAnnealingWarmRestarts\",\"args\":{\"T_0\":50,\"T_mult\":2}}'",
                'warm restarts T_0=50 T_mult=2, 350 epochs (cycles 50/100/200)'),
    'wr100na': ('B_restarts', 300, "--lr-scheduler '{\"type\":\"CosineAnnealingWarmRestarts\",\"args\":{\"T_0\":100}}' "
                "--optimizer-args '{\"amsgrad\":false}'", 'warm restarts T_0=100 with plain Adam (amsgrad off)'),
    'phys0':   ('D_variants', 300, '--physics-only', 'physics-only (residual_rank 0, dim_z_aux 0), cosine 300 [recipe variant]'),
    'randinit': ('D_variants', 300, '--random-init', 'honest per-seed random start via init_sources, cosine 300 [needs user OK]'),
    'lsamp':   ('D_variants', 300, '--latent-sampling', 'z_phy sampling on with KL weight 0, cosine 300 [recipe variant]'),
}

PBS_TEMPLATE = """#!/bin/bash
# Usage:       qsub {pbs_rel}
# Description: Honest K=2-only tuning on K2_separated_static (no truth, penalties off): {what}, seed {seed}
#              Generated by generate_k2_tune_jobs.py -- do not edit by hand.
# Date:        2026-10-09
#PBS -N {job_name}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l nodes=1:ppn=2
#PBS -l walltime=01:00:00
#PBS -l mem=8gb
#PBS -j oe
#PBS -o logs/{job_name}_pbs.log

set -e
cd "$PBS_O_WORKDIR"
source /eos-rs/miniconda3/etc/profile.d/conda.sh
conda activate pila
export PYTHONPATH="${{PYTHONPATH}}:$PBS_O_WORKDIR"
export MKL_THREADING_LAYER=GNU
export OMP_NUM_THREADS=2

echo "[{job_name}] host=$(hostname) env=$CONDA_DEFAULT_ENV start $(date)"
{command}
echo "[{job_name}] done $(date)"
"""


def parse_seeds(text):
    """'1-8,123' -> [1..8, 123]."""
    seeds = []
    for part in text.split(','):
        if '-' in part:
            low, high = part.split('-')
            seeds += list(range(int(low), int(high) + 1))
        else:
            seeds.append(int(part))
    return seeds


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--arms', nargs='+', default=list(ARMS))
    parser.add_argument('--seeds', default='1-16')
    parser.add_argument('--out-dir', default='jobs/multisource_k2_tune')
    args = parser.parse_args()
    unknown = [arm for arm in args.arms if arm not in ARMS]
    if unknown:
        raise ValueError(f"unknown arms {unknown}; known {list(ARMS)}")
    out_dir = os.path.join(PROJECT_ROOT, args.out_dir)
    os.makedirs(out_dir, exist_ok=True)
    # --- Pre-check every target path so an existing file never leaves a half-written set ---
    clashes = [os.path.join(args.out_dir, f'k2tune_{arm}_s{seed}.pbs') for arm in args.arms for seed in parse_seeds(args.seeds)
               if os.path.exists(os.path.join(PROJECT_ROOT, args.out_dir, f'k2tune_{arm}_s{seed}.pbs'))]
    if clashes:
        raise FileExistsError(f"{len(clashes)} job file(s) exist, e.g. {clashes[0]}; not overwriting")
    group_scripts = {}
    n_written = 0
    for arm in args.arms:
        group, epochs, flags, what = ARMS[arm]
        for seed in parse_seeds(args.seeds):
            job_name = f'k2tune_{arm}_s{seed}'
            pbs_rel = os.path.join(args.out_dir, f'{job_name}.pbs')
            if os.path.exists(os.path.join(PROJECT_ROOT, pbs_rel)):
                raise FileExistsError(f"{pbs_rel} exists; not overwriting")
            command = (f"python -u run_k2_tune.py --album {ALBUM} --seed {seed} --epochs {epochs} "
                       f"--tag k2tune_{arm}_seed{seed} --save-root {SAVE_ROOT} {flags}")
            with open(os.path.join(PROJECT_ROOT, pbs_rel), 'w') as handle:
                handle.write(PBS_TEMPLATE.format(pbs_rel=pbs_rel, what=what, seed=seed, job_name=job_name, command=command))
            group_scripts.setdefault(group, []).append(pbs_rel)
            n_written += 1
    for group, scripts in group_scripts.items():
        submit_path = os.path.join(out_dir, f'submit_{group}.sh')
        if os.path.exists(submit_path):
            raise FileExistsError(f"{submit_path} exists; not overwriting")
        with open(submit_path, 'w') as handle:
            handle.write('#!/bin/bash\nset -e\ncd "%s"\n' % PROJECT_ROOT + ''.join(f'qsub {path}\n' for path in scripts))
        os.chmod(submit_path, 0o755)
    print(f"Done. Wrote {n_written} PBS scripts + {len(group_scripts)} submit scripts to {args.out_dir}/ (nothing submitted)")


if __name__ == '__main__':
    main()
