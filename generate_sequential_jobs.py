#!/usr/bin/env python
# Usage:       python generate_sequential_jobs.py [--albums-dir synthetic/multisource/pila_stacks_v2/albums]
#                  [--albums-per-job 3] [--kmax 3] [--tag main] [--out-dir jobs/multisource_seq]
#              then (after review):  bash jobs/multisource_seq/submit_all.sh
# Description: Step 3 of the sequential multi-source plan. Writes PBS jobs that run
#              run_sequential_album.py (K = 1 .. kmax, each warm-started from K-1, auto-dumped) on every
#              album (39 calibration + 18 evaluation), a few albums per job, all jobs independent so they
#              run in parallel. Nothing is submitted here: submit_all.sh is written for the user to run
#              (or for Claude to run after the user approves).
# Notes:       One album (K = 1..3, 150 epochs each) takes ~5 min on CPU (~90-100 s per K measured on
#              2026-10-06), so 3 albums per job ~ 15-20 min; walltime 2 h leaves a wide margin.
#              Resumable: run_sequential_album.py skips any K whose fit already exists.
# Date:        2026-10-06

import argparse
import glob
import os

PBS_TEMPLATE = """#!/bin/bash
# Usage:       qsub {pbs_rel}
# Description: Sequential multi-source PILA (K = 1..{kmax}) on {n} album(s): {albums_short}
#              Generated by generate_sequential_jobs.py -- do not edit by hand.
# Date:        2026-10-06
#PBS -N {job_name}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l nodes=1:ppn=2
#PBS -l walltime=02:00:00
#PBS -l mem=8gb
#PBS -j oe
#PBS -o logs/{job_name}_pbs.log

set -e
cd "$PBS_O_WORKDIR"
source /eos-rs/miniconda3/etc/profile.d/conda.sh
conda activate pila
export PYTHONPATH="${{PYTHONPATH}}:$PBS_O_WORKDIR"
export MKL_THREADING_LAYER=GNU
export OMP_NUM_THREADS=2

echo "[{job_name}] host=$(hostname) env=$CONDA_DEFAULT_ENV start $(date)"
{commands}
echo "[{job_name}] done $(date)"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--albums-dir', default='synthetic/multisource/pila_stacks_v2/albums')
    parser.add_argument('--albums-per-job', type=int, default=3)
    parser.add_argument('--kmax', type=int, default=3)
    parser.add_argument('--tag', default='main')
    parser.add_argument('--recipe', default='standard', choices=['standard', 'original', 'synth_v1'])
    parser.add_argument('--out-dir', default='jobs/multisource_seq')
    args = parser.parse_args()
    albums = sorted(glob.glob(os.path.join(args.albums_dir, '*.npz')))
    if not albums:
        raise FileNotFoundError(f"no albums in {args.albums_dir}")
    os.makedirs(args.out_dir, exist_ok=True)
    print(f"[1/2] {len(albums)} albums -> jobs of {args.albums_per_job}")
    pbs_paths = []
    for j in range(0, len(albums), args.albums_per_job):
        chunk = albums[j:j + args.albums_per_job]
        job_name = f'seq_{args.tag}_{j // args.albums_per_job:02d}'
        pbs_rel = os.path.join(args.out_dir, f'{job_name}.pbs')
        if os.path.exists(pbs_rel):
            raise FileExistsError(f"{pbs_rel} exists; not overwriting")
        commands = '\n'.join(
            f'python -u run_sequential_album.py --album {a} --kmax {args.kmax} --tag {args.tag} --recipe {args.recipe}'
            for a in chunk)
        with open(pbs_rel, 'w') as f:
            f.write(PBS_TEMPLATE.format(pbs_rel=pbs_rel, kmax=args.kmax, n=len(chunk), job_name=job_name,
                                        albums_short=', '.join(os.path.basename(a)[:-4] for a in chunk),
                                        commands=commands))
        pbs_paths.append(pbs_rel)
    submit = os.path.join(args.out_dir, 'submit_all.sh')
    if os.path.exists(submit):
        raise FileExistsError(f"{submit} exists; not overwriting")
    with open(submit, 'w') as f:
        f.write("#!/bin/bash\n# Submit all sequential multi-source jobs (independent, run in parallel).\nset -e\n"
                f'cd "{os.path.abspath(".")}"\n' + ''.join(f'qsub {p}\n' for p in pbs_paths))
    print(f"[2/2] Wrote {len(pbs_paths)} PBS scripts and {submit}")
    print(f"Done. Output saved to {args.out_dir}/")


if __name__ == '__main__':
    main()
