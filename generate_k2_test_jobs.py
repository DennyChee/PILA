#!/usr/bin/env python
# Usage:       python generate_k2_test_jobs.py [--seeds 1 2 3 4 5 6 7 8] [--out-dir jobs/multisource_k2_stepwise]
# Description: PBS scripts (NOT submitted) for the K=2 initialisation test on K2_separated_static: one job per seed
#              (standard recipe, K=1 -> K=2 warm start, --seed S) plus one job that starts K=2 at the TRUTH
#              (--init-sources). Never overwrites existing files. Submit by hand after review: bash <out-dir>/submit_all.sh
# Date:        2026-10-08

import argparse
import json
import os

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
ALBUM = 'synthetic/multisource/clean_scenarios/K2_separated_static.npz'
SAVE_ROOT = 'saved/multisource_k2_multiseed'

PBS_TEMPLATE = """#!/bin/bash
# Usage:       qsub {pbs_rel}
# Description: K=2 initialisation test on K2_separated_static: {what}
#              Generated by generate_k2_test_jobs.py -- do not edit by hand.
# Date:        2026-10-08
#PBS -N {job_name}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l nodes=1:ppn=2
#PBS -l walltime=01:00:00
#PBS -l mem=8gb
#PBS -j oe
#PBS -o logs/{job_name}_pbs.log

set -e
cd "$PBS_O_WORKDIR"
source /eos-rs/miniconda3/etc/profile.d/conda.sh
conda activate pila
export PYTHONPATH="${{PYTHONPATH}}:$PBS_O_WORKDIR"
export MKL_THREADING_LAYER=GNU
export OMP_NUM_THREADS=2

echo "[{job_name}] host=$(hostname) env=$CONDA_DEFAULT_ENV start $(date)"
{command}
echo "[{job_name}] done $(date)"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--seeds', type=int, nargs='+', default=[1, 2, 3, 4, 5, 6, 7, 8])
    parser.add_argument('--out-dir', default='jobs/multisource_k2_stepwise')
    args = parser.parse_args()
    truth_path = os.path.join(PROJECT_ROOT, ALBUM[:-4] + '_truth.json')
    if not os.path.exists(truth_path):
        raise FileNotFoundError(truth_path)
    with open(truth_path) as handle:
        truth = json.load(handle)
    init_sources = [[s['xcen_km'], s['ycen_km'], s['depth_km'], s['dV_m3']] for s in truth['sources']]
    os.makedirs(os.path.join(PROJECT_ROOT, args.out_dir), exist_ok=True)
    jobs = [(f'k2ms_s{seed}', f'standard recipe, seed {seed} (K=1 then K=2 warm start)',
             f'python -u run_sequential_album.py --album {ALBUM} --kmax 2 --seed {seed} --tag seed{seed} --save-root {SAVE_ROOT}')
            for seed in args.seeds]
    jobs.append(('k2ms_truth', 'K=2 started at the TRUE sources (seed 123, standard recipe incl. KL / dV-L1 / curvature)',
                 f"python -u run_sequential_album.py --album {ALBUM} --init-sources '{json.dumps(init_sources)}' "
                 f"--tag truthinit --save-root {SAVE_ROOT}"))
    jobs.append(('k2ms_truth_nopen', 'K=2 started at the TRUE sources with KL, dV-L1 and curvature switched OFF (control: pure reconstruction loss)',
                 f"python -u run_sequential_album.py --album {ALBUM} --init-sources '{json.dumps(init_sources)}' "
                 f"--no-penalties --tag truthinit_nopen --save-root {SAVE_ROOT}"))
    written = []
    for job_name, what, command in jobs:
        pbs_rel = os.path.join(args.out_dir, f'{job_name}.pbs')
        if os.path.exists(os.path.join(PROJECT_ROOT, pbs_rel)):
            raise FileExistsError(f"{pbs_rel} exists; not overwriting")
        with open(os.path.join(PROJECT_ROOT, pbs_rel), 'w') as handle:
            handle.write(PBS_TEMPLATE.format(pbs_rel=pbs_rel, what=what, job_name=job_name, command=command))
        written.append(pbs_rel)
    submit = os.path.join(PROJECT_ROOT, args.out_dir, 'submit_all.sh')
    if os.path.exists(submit):
        raise FileExistsError(f"{submit} exists; not overwriting")
    with open(submit, 'w') as handle:
        handle.write('#!/bin/bash\nset -e\ncd "%s"\n' % PROJECT_ROOT + ''.join(f'qsub {p}\n' for p in written))
    print(f"Done. Wrote {len(written)} PBS scripts + submit_all.sh to {args.out_dir}/ (nothing submitted)")


if __name__ == '__main__':
    main()
