#!/usr/bin/env python
# Usage:       python classical_comsol/generate_comsol_iokada_jobs.py [--topo varying_depth]
#                  [--surface cone] [--tracks asc desc] [--chunks 4]
# Description: Write PBS jobs (one per surface/track/chunk) for the classical SA + MCMC Mogi
#              inversion of the COMSOL wk6 shims with iokada_agung_residuals.m, WITH
#              ('varying_depth') or WITHOUT ('none') the W&W topography correction, via
#              classical_comsol/run_comsol_iokada_group.m. Writes a submit-all script; never
#              submits itself.
# Date:        2026-10-12

import argparse
import os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

PBS_TEMPLATE = """#!/bin/bash
# Classical SA + MCMC Mogi inversion (iokada_agung_residuals.m, TopoCorrection={topo}),
# COMSOL wk6 {surface} {track}, chunk {chunk}/{n_chunks}. Generated by
# classical_comsol/generate_comsol_iokada_jobs.py -- edit the generator, not this file.
#PBS -N {job_name}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l nodes=1:ppn=4
#PBS -l walltime={walltime}
#PBS -l mem=16gb
#PBS -j oe
#PBS -o {log_path}

set -e
cd "{repo}"
echo "[{job_name}] Host: $(hostname)  Job: $PBS_JOBID  Start: $(date)"
source /usr/local/Modules/init/bash
module load matlab/R2023b-u9

# Pin BLAS/OpenMP to the allocation so runtimes are repeatable.
export NCPUS=4 OMP_NUM_THREADS=4 MKL_NUM_THREADS=4
export SHIM_DIR="{repo}/exported_comsol/iokada_shims"
export EXPORT_DIR="{repo}/exported_comsol/single"
export OUT_DIR="{repo}/classic_out_comsol_topo/{topo}"
export GROUP_GLOB="*_{surface}_{track}_*"
export TOPO={topo}
export CHUNK_INDEX={chunk} CHUNK_COUNT={n_chunks}
export NBAY=10000 SEED=1

# try/catch + -batch: a MATLAB error must fail the job, not exit 0 silently.
matlab -batch "try; run('classical_comsol/run_comsol_iokada_group.m'); catch ME; disp(getReport(ME)); exit(1); end"
echo "[{job_name}] Finished: $(date)"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--topo', default='varying_depth', choices=['none', 'varying_depth'])
    parser.add_argument('--surface', default='cone', choices=['cone', 'flat'])
    parser.add_argument('--tracks', nargs='+', default=['asc', 'desc'], choices=['asc', 'desc', 'joint'])
    parser.add_argument('--chunks', type=int, default=4)
    args = parser.parse_args()

    pbs_dir = os.path.join(REPO, 'jobs', 'comsol_classical_topo')
    log_dir = os.path.join(REPO, 'logs', 'comsol_classical_topo')
    os.makedirs(pbs_dir, exist_ok=True)
    os.makedirs(log_dir, exist_ok=True)
    print(f"[1/2] Writing jobs to {pbs_dir} (TopoCorrection={args.topo}) ...")
    job_paths = []
    topo_tag = 'T' if args.topo == 'varying_depth' else 'F'
    for track in args.tracks:
        for chunk in range(1, args.chunks + 1):
            name = f'classic_{args.topo}_{args.surface}_{track}_c{chunk}'
            job_path = os.path.join(pbs_dir, f'{name}.pbs')
            with open(job_path, 'w') as fh:
                fh.write(PBS_TEMPLATE.format(
                    topo=args.topo, surface=args.surface, track=track, chunk=chunk,
                    n_chunks=args.chunks, repo=REPO,
                    log_path=os.path.join(log_dir, f'{name}.log'),
                    walltime='10:00:00' if track == 'joint' else '06:00:00',   # joint = 2x points
                    job_name=f'cl{topo_tag}_{args.surface}_{track[0]}{chunk}'))   # <= 15 chars
            job_paths.append(job_path)
    submit_all = os.path.join(pbs_dir, f'submit_all_{args.topo}_{args.surface}_{"_".join(args.tracks)}.sh')
    with open(submit_all, 'w') as fh:
        fh.write("#!/bin/bash\n# Submit every job of this group (run from the repo root)\nset -e\n"
                 + "".join(f'qsub "{path}"\n' for path in job_paths))
    os.chmod(submit_all, 0o755)
    print(f"[2/2] {len(job_paths)} jobs; submit with: bash {submit_all}")
    print("Done.")


if __name__ == '__main__':
    main()
