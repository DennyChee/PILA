#!/usr/bin/env python
# Usage:       python generate_comsol_classical_jobs.py [--exported exported_comsol]
#                  [--out-dir classic_out_comsol] [--pbs-dir jobs/comsol_classical]
#                  [--chunks 4] [--submit]
# Description: Write one PBS job per (surface, track, chunk) for the classical SA + MCMC
#              Mogi inversion of the COMSOL wk6 exports (export_comsol_points.py), running
#              classical_comsol/run_comsol_group.m. 2 surfaces x 3 tracks (asc / desc / joint)
#              x --chunks parallel jobs. Writes a submit_all.sh; submits only with --submit.
# Date:        2026-10-02
#
# Resource notes: the cid1000 pilot measured ~200 s per 40401-point scene (SA 7 s +
# MCMC 191 s, 4 threads), so 10 single-track scenes ~35 min; joint scenes are 2x the
# points (~70 min per 10). Walltimes below leave >2.5x headroom.

import argparse
import glob
import os
import subprocess

CURRENT_DIR = os.path.dirname(os.path.abspath(__file__))
SURFACES = ('flat', 'cone')
TRACKS = ('asc', 'desc', 'joint')
WALLTIME = {'asc': '03:00:00', 'desc': '03:00:00', 'joint': '05:00:00'}

PBS_TEMPLATE = """#!/bin/bash
# Classical SA + MCMC Mogi inversion, COMSOL wk6 {surface} {track}, chunk {chunk}/{n_chunks}.
# Generated by generate_comsol_classical_jobs.py -- edit the generator, not this file.
#PBS -N {job_name}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l nodes=1:ppn=4
#PBS -l walltime={walltime}
#PBS -l mem=16gb
#PBS -j oe
#PBS -o {log_path}

set -e
cd "{repo}"

echo "[{job_name}] Host: $(hostname)  Job: $PBS_JOBID  Start: $(date)"
source /usr/local/Modules/init/bash
module load matlab/R2023b-u9

# Pin BLAS/OpenMP to the allocation so runtimes are repeatable (compared against PILA).
export NCPUS=4 OMP_NUM_THREADS=4 MKL_NUM_THREADS=4
export EXPORT_DIR="{export_dir}"
export OUT_DIR="{out_dir}"
export GROUP_GLOB="{group_glob}"
export CHUNK_INDEX={chunk} CHUNK_COUNT={n_chunks}
export NBAY=10000 SEED=1 START_MODE=centre

# try/catch + -batch: a MATLAB error must fail the job, not exit 0 silently.
matlab -batch "try; run('classical_comsol/run_comsol_group.m'); catch ME; disp(getReport(ME)); exit(1); end"

# Belt and braces: the chunk's summary CSV must exist.
SUMMARY="{out_dir}/_group_summary_{glob_tag}_chunk$(printf '%02d' {chunk})of$(printf '%02d' {n_chunks}).csv"
if [ ! -s "$SUMMARY" ]; then
  echo "[{job_name}] ERROR: summary missing: $SUMMARY" >&2
  exit 1
fi
echo "[{job_name}] Output OK: $SUMMARY  Finished: $(date)"
"""


def main():
    parser = argparse.ArgumentParser(description='Write PBS jobs for COMSOL classical inversions')
    parser.add_argument('--exported', default='exported_comsol')
    parser.add_argument('--out-dir', default='classic_out_comsol')
    parser.add_argument('--pbs-dir', default='jobs/comsol_classical')
    parser.add_argument('--log-dir', default='logs/comsol_classical')
    parser.add_argument('--chunks', type=int, default=4, help='parallel jobs per (surface, track)')
    parser.add_argument('--submit', action='store_true', help='qsub every job (default: write only)')
    args = parser.parse_args()

    # --- [1/2] Write one job per (surface, track, chunk) ---
    print(f"[1/2] Writing jobs to {args.pbs_dir} ({args.chunks} chunks per group) ...")
    os.makedirs(args.pbs_dir, exist_ok=True)
    os.makedirs(os.path.join(CURRENT_DIR, args.log_dir), exist_ok=True)   # PBS -o path is repo-rooted
    job_paths = []
    for surface in SURFACES:
        for track in TRACKS:
            sub_dir = 'joint' if track == 'joint' else 'single'
            export_dir = os.path.join(CURRENT_DIR, args.exported, sub_dir)
            group_glob = f'comsol_wk6_cid*_{surface}_{track}_mogi'
            n_scenes = len(glob.glob(os.path.join(export_dir, group_glob + '.mat')))
            if n_scenes == 0:
                raise FileNotFoundError(f"no exports for {surface}/{track} in {export_dir}; "
                                        f"run export_comsol_points.py first")
            # Same tag rule as run_comsol_group.m: drop '*' and '_' from the glob.
            glob_tag = group_glob.replace('*', '').replace('_', '')
            for chunk in range(1, args.chunks + 1):
                job_name = f'clc_{surface}_{track}_{chunk}'
                job_path = os.path.join(args.pbs_dir, f'{job_name}.pbs')
                with open(job_path, 'w') as fh:
                    fh.write(PBS_TEMPLATE.format(
                        surface=surface, track=track, chunk=chunk, n_chunks=args.chunks,
                        job_name=job_name, walltime=WALLTIME[track], repo=CURRENT_DIR,
                        log_path=os.path.join(CURRENT_DIR, args.log_dir, f'{job_name}.log'),
                        export_dir=export_dir,
                        out_dir=os.path.join(CURRENT_DIR, args.out_dir, f'{surface}_{track}'),
                        group_glob=group_glob, glob_tag=glob_tag))
                job_paths.append(job_path)
            print(f"  {surface}/{track}: {n_scenes} scenes -> {args.chunks} jobs")

    submit_all = os.path.join(args.pbs_dir, 'submit_all.sh')
    with open(submit_all, 'w') as fh:
        fh.write('#!/bin/bash\nset -e\n')
        fh.writelines(f'qsub "{path}"\n' for path in job_paths)
    os.chmod(submit_all, 0o755)
    print(f"  wrote {len(job_paths)} jobs + {submit_all}")

    # --- [2/2] Optional submission ---
    if not args.submit:
        print("[2/2] Not submitted (pass --submit, or run submit_all.sh)")
    else:
        print("[2/2] Submitting ...")
        for path in job_paths:
            job_id = subprocess.run(['qsub', path], check=True, capture_output=True,
                                    text=True).stdout.strip()
            print(f"  {os.path.basename(path)} -> {job_id}")
    print(f"Done. Jobs in {args.pbs_dir}/")


if __name__ == '__main__':
    main()
