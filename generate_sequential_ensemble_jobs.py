#!/usr/bin/env python
# Usage:       python generate_sequential_ensemble_jobs.py [--noise-set E1] [--members 10] [--kmax 3]
#                  [--bootstrap-frac 0.5] [--bootstrap-block 8] [--out-dir jobs/multisource_seq_ens]
#              then (after review):  bash jobs/multisource_seq_ens/submit_all.sh
# Description: Step 4 of the sequential multi-source plan. Ensemble of M members per evaluation album
#              (default: noise set E1, scenarios S0..S5). Member m = RNG seed m + a spatial
#              block-subsample of the pixels (bootstrap_k = frac x 16384 cells, in bootstrap_block-square
#              tiles, seed m). Each member runs the full K = 1..kmax sequence; aggregate_sequential_ensemble.py
#              then gives per-source support (fraction of members that keep a source there) and P(K = k).
# Notes:       8 x 8-px tiles (~3 x 2.6 km) are about one noise correlation length, so a member drops whole
#              correlated atmospheric patches rather than independent pixels (respects APS correlation).
#              Each member is evaluated on the FULL album by sequential_select_k.py (re-render from params).
#              One job per (album, member): ~5 min each.
# Date:        2026-10-06

import argparse
import glob
import os

PBS_TEMPLATE = """#!/bin/bash
# Usage:       qsub {pbs_rel}
# Description: Sequential multi-source PILA ensemble member {member} (seed {member}, block-subsample
#              {k_px} px in {block}x{block} tiles) on {album}. Generated by generate_sequential_ensemble_jobs.py.
# Date:        2026-10-06
#PBS -N {job_name}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l nodes=1:ppn=2
#PBS -l walltime=01:00:00
#PBS -l mem=8gb
#PBS -j oe
#PBS -o logs/{job_name}_pbs.log

set -e
cd "$PBS_O_WORKDIR"
source /eos-rs/miniconda3/etc/profile.d/conda.sh
conda activate pila
export PYTHONPATH="${{PYTHONPATH}}:$PBS_O_WORKDIR"
export MKL_THREADING_LAYER=GNU
export OMP_NUM_THREADS=2

echo "[{job_name}] host=$(hostname) start $(date)"
python -u run_sequential_album.py --album {album_path} --kmax {kmax} --tag ens_m{member:02d} --seed {member} \\
    --bootstrap-k {k_px} --bootstrap-block {block} --bootstrap-seed {member}
echo "[{job_name}] done $(date)"
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--albums-dir', default='synthetic/multisource/pila_stacks_v2/albums')
    parser.add_argument('--noise-set', default='E1')
    parser.add_argument('--members', type=int, default=10)
    parser.add_argument('--kmax', type=int, default=3)
    parser.add_argument('--bootstrap-frac', type=float, default=0.5)
    parser.add_argument('--bootstrap-block', type=int, default=8)
    parser.add_argument('--n-pixels', type=int, default=128 * 128)
    parser.add_argument('--out-dir', default='jobs/multisource_seq_ens')
    args = parser.parse_args()
    albums = sorted(glob.glob(os.path.join(args.albums_dir, f'{args.noise_set}_S*.npz')))
    if not albums:
        raise FileNotFoundError(f"no {args.noise_set}_S*.npz albums in {args.albums_dir}")
    os.makedirs(args.out_dir, exist_ok=True)
    k_px = int(args.bootstrap_frac * args.n_pixels)
    print(f"[1/2] {len(albums)} albums x {args.members} members, {k_px} px per member in "
          f"{args.bootstrap_block}x{args.bootstrap_block} tiles")
    pbs_paths = []
    for album_path in albums:
        album = os.path.basename(album_path)[:-4]
        for member in range(1, args.members + 1):
            job_name = f'ens_{album.split("_")[1]}_m{member:02d}'          # e.g. ens_S3_m04
            pbs_rel = os.path.join(args.out_dir, f'{job_name}.pbs')
            if os.path.exists(pbs_rel):
                raise FileExistsError(f"{pbs_rel} exists; not overwriting")
            with open(pbs_rel, 'w') as f:
                f.write(PBS_TEMPLATE.format(pbs_rel=pbs_rel, member=member, k_px=k_px, block=args.bootstrap_block,
                                            album=album, job_name=job_name, album_path=album_path, kmax=args.kmax))
            pbs_paths.append(pbs_rel)
    submit = os.path.join(args.out_dir, 'submit_all.sh')
    if os.path.exists(submit):
        raise FileExistsError(f"{submit} exists; not overwriting")
    with open(submit, 'w') as f:
        f.write("#!/bin/bash\n# Submit all ensemble members (independent, run in parallel).\nset -e\n"
                f'cd "{os.path.abspath(".")}"\n' + ''.join(f'qsub {p}\n' for p in pbs_paths))
    print(f"[2/2] Wrote {len(pbs_paths)} PBS scripts and {submit}")
    print(f"Done. Output saved to {args.out_dir}/")


if __name__ == '__main__':
    main()
