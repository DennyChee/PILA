#!/usr/bin/env python
# Usage:       python generate_k2_noisy_jobs.py [--arms base wr100] [--seeds 1-16] \
#                  [--album synthetic/multisource/pila_stacks_v2/albums/E1_S3_K2_separated.npz] [--tag-prefix noisyE1] \
#                  [--out-dir jobs/multisource_k2_tune_noisyE1]
# Description: Writes PBS scripts (NOT submitted) for the honest K=2-only tuning study on the NOISY twin of
#              K2_separated_static. Reuses the arm definitions and PBS template of generate_k2_tune_jobs.py (no
#              existing file edited); only the album and tag prefix change. One submit script submit_<prefix>.sh.
#              Tag = k2tune_<prefix>_<arm>_seed<S>, save root saved/multisource_k2_tune/. Never overwrites files.
#              --penalties-on switches the driver to run_k2_tune_pen.py (standard penalties kept).
# Date:        2026-10-09

import argparse
import os

from generate_k2_tune_jobs import ARMS, PBS_TEMPLATE, SAVE_ROOT, parse_seeds

PROJECT_ROOT = os.path.dirname(os.path.abspath(__file__))
DEFAULT_ALBUM = 'synthetic/multisource/pila_stacks_v2/albums/E1_S3_K2_separated.npz'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--arms', nargs='+', default=['base', 'wr100'])
    parser.add_argument('--seeds', default='1-16')
    parser.add_argument('--album', default=DEFAULT_ALBUM)
    parser.add_argument('--tag-prefix', default='noisyE1')
    parser.add_argument('--out-dir', default='jobs/multisource_k2_tune_noisyE1')
    parser.add_argument('--penalties-on', action='store_true',
                        help='use run_k2_tune_pen.py (standard curvature/dV-L1/KL penalties ON) instead of run_k2_tune.py')
    parser.add_argument('--job-prefix', default=None, help='short PBS job-name prefix (default k2n<last 2 chars of tag prefix>)')
    args = parser.parse_args()

    # --- Validate inputs ---
    unknown = [arm for arm in args.arms if arm not in ARMS]
    if unknown:
        raise ValueError(f"unknown arms {unknown}; known {list(ARMS)}")
    if not os.path.exists(os.path.join(PROJECT_ROOT, args.album)):
        raise FileNotFoundError(args.album)
    album_name = os.path.splitext(os.path.basename(args.album))[0]
    seeds = parse_seeds(args.seeds)

    # --- Pre-check every target (job file and run dir) so a clash never leaves a half-written set ---
    jobs = []
    for arm in args.arms:
        for seed in seeds:
            job_prefix = args.job_prefix or f'k2n{args.tag_prefix[-2:]}'
            job_name = f'{job_prefix}_{arm}_s{seed}'          # short: qstat truncates job names
            tag = f'k2tune_{args.tag_prefix}_{arm}_seed{seed}'
            pbs_rel = os.path.join(args.out_dir, f'{job_name}.pbs')
            for path in (pbs_rel, os.path.join(SAVE_ROOT, tag)):
                if os.path.exists(os.path.join(PROJECT_ROOT, path)):
                    raise FileExistsError(f"{path} exists; not overwriting")
            jobs.append((arm, seed, job_name, tag, pbs_rel))
    submit_rel = os.path.join(args.out_dir, f'submit_{args.tag_prefix}.sh')
    if os.path.exists(os.path.join(PROJECT_ROOT, submit_rel)):
        raise FileExistsError(f"{submit_rel} exists; not overwriting")

    # --- Write PBS scripts (template text names the clean scene, so patch the description line) ---
    os.makedirs(os.path.join(PROJECT_ROOT, args.out_dir), exist_ok=True)
    driver = 'run_k2_tune_pen.py' if args.penalties_on else 'run_k2_tune.py'
    template = (PBS_TEMPLATE.replace('on K2_separated_static', f'on {album_name} (noisy twin)')
                .replace('Generated by generate_k2_tune_jobs.py', 'Generated by generate_k2_noisy_jobs.py'))
    if args.penalties_on:
        template = template.replace('penalties off', 'standard penalties ON: curvature 15000, dV-L1 300 u, KL 0.5')
    for arm, seed, job_name, tag, pbs_rel in jobs:
        _group, epochs, flags, what = ARMS[arm]
        command = (f"python -u {driver} --album {args.album} --seed {seed} --epochs {epochs} "
                   f"--tag {tag} --save-root {SAVE_ROOT} {flags}")
        with open(os.path.join(PROJECT_ROOT, pbs_rel), 'w') as handle:
            handle.write(template.format(pbs_rel=pbs_rel, what=what, seed=seed, job_name=job_name, command=command))
    with open(os.path.join(PROJECT_ROOT, submit_rel), 'w') as handle:
        handle.write('#!/bin/bash\nset -e\ncd "%s"\n' % PROJECT_ROOT + ''.join(f'qsub {job[4]}\n' for job in jobs))
    os.chmod(os.path.join(PROJECT_ROOT, submit_rel), 0o755)
    print(f"Done. Wrote {len(jobs)} PBS scripts + {submit_rel} (nothing submitted)")


if __name__ == '__main__':
    main()
