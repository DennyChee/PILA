#!/bin/bash
# Usage:       tests/integration/submit_pipeline_matrix.sh [manifest] [--dry-run]
#              (default manifest: runs/_test_scenarios/manifest.csv)
# Description: Submit the pipeline test matrix as ONE PBS JOB PER SCENARIO (all methods inside a job), all
#              writing into one shared directory runs/_test_matrix/<timestamp>/. When every job has finished, run
#                  python tests/integration/run_pipeline_matrix.py --aggregate --out <that directory> \
#                      --manifest <manifest>
#              to combine the per-scenario matrices, run the checks and compare.py (seconds, done interactively).
#              Account / queue as the PILA campaign jobs (eos_btaisne, qintel_wfly). --dry-run writes the PBS
#              scripts without submitting.
# Date:        2026-11-23
set -e

MANIFEST="${1:-runs/_test_scenarios/manifest.csv}"
DRY_RUN="${2:-}"
PILA_ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$PILA_ROOT"
STAMP=$(date +%Y%m%d_%H%M%S)
OUT="$PILA_ROOT/runs/_test_matrix/$STAMP"
PBS_DIR="$OUT/pbs"
mkdir -p "$PBS_DIR" "$OUT/logs"

echo "[1/2] Writing one PBS script per scenario of $MANIFEST into $PBS_DIR ..."
SCENARIOS=$(python3 -c "import csv; print(' '.join(r['scenario_id'] for r in csv.DictReader(open('$MANIFEST'))))")
for SID in $SCENARIOS; do
    cat > "$PBS_DIR/matrix_$SID.pbs" <<EOF
#!/bin/bash
#PBS -N mtx_${SID:0:11}
#PBS -P eos_btaisne
#PBS -q qintel_wfly
#PBS -l select=1:ncpus=8:mem=32gb
#PBS -l walltime=08:00:00
#PBS -j oe
#PBS -o $OUT/logs/pbs_$SID.log
# Pipeline test matrix, scenario $SID (generated by tests/integration/submit_pipeline_matrix.sh)
set -e
cd "$PILA_ROOT"
source /eos-rs/miniconda3/etc/profile.d/conda.sh
conda activate pila
source /usr/local/Modules/init/bash 2>/dev/null || true
module load matlab/R2023b-u9
export MATLAB_BIN=\$(command -v matlab)
export MKL_THREADING_LAYER=GNU
echo "[matrix $SID] host=\$(hostname) env=\$CONDA_DEFAULT_ENV matlab=\$MATLAB_BIN start \$(date)"
python -u tests/integration/run_pipeline_matrix.py --manifest "$MANIFEST" --scenarios "$SID" --out "$OUT" --tag "$SID"
echo "[matrix $SID] done \$(date)"
EOF
done
ls "$PBS_DIR"

if [ "$DRY_RUN" = "--dry-run" ]; then
    echo "[2/2] Dry run: nothing submitted. Output dir $OUT"
    exit 0
fi
echo "[2/2] Submitting ..."
for SCRIPT in "$PBS_DIR"/*.pbs; do
    JOB_ID=$(qsub "$SCRIPT")
    echo "  $(basename "$SCRIPT") -> $JOB_ID"
    echo "$JOB_ID $(basename "$SCRIPT")" >> "$OUT/submitted_job_ids.txt"
done
echo "Done. When all jobs finish: python tests/integration/run_pipeline_matrix.py --aggregate --out $OUT --manifest $MANIFEST"
